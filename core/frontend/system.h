/* What a console gives the SDL3 frontend (sdl3_main.c): one `System` table
 * per console, exported by its systems/<id>/frontend.c. A program lists the
 * systems it links (system_list, written by CMake: retrocast every system
 * in SYSTEMS, a recompiled game its own one); the frontend owns the window,
 * sound, input, pacing, settings file and state keys, the system everything
 * else. The frontend calls frame, reset, key and the state functions from
 * its emulator thread or under its lock, never at the same time. */
#ifndef CORE_SYSTEM_H
#define CORE_SYSTEM_H

#include <stddef.h>
#include <stdint.h>

#include "detect.h"
#include "input_log.h"
#include "settings.h"

typedef struct {
    int width, height;        /* frame buffer, XRGB8888 */
    int cols, lines;          /* the visible part, centred in it */
    double fps;               /* frames per second the game runs at */
    double aspect;            /* shown pixel width / height (1 = square) */
    int sample_rate;          /* float samples a second, per channel */
    int channels;             /* 1 = mono, 2 = stereo (samples interleaved, left first) */
    int players;              /* pads the game reads: 2 (0 is taken as 2) or 4 */
    char name[256];           /* the game, for the window title */
    char tag[16];             /* after it: "Game (NTSC)" */
    char state_path[1024];    /* F2 / F4 */
} SysInfo;

typedef struct {
    /* the id (as recordings name the system: core/input_log.h), the file
     * extensions and the detector over the file's bytes (core/detect.h) */
    const SystemDetector *detector;
    const char *app;          /* the settings file is <app>.ini next to the program */
    /* The system's own settings: offered every key the frontend does not
     * know (1 = taken), and appended to the default settings file. */
    const char *settings;
    int (*setting)(const char *key, const char *value);
    /* Load the game: `path` from the command line, or NULL for the one the
     * program embeds. Called after the settings are loaded. 0 on success,
     * else a message in err (2: a usage message). */
    int (*open)(const char *path, const Settings *cfg, SysInfo *info, char *err, size_t errlen);
    void (*reset)(void);
    /* One frame with this input (InputFrame: the PAD_* buttons; the system
     * reads the ones its pad has): the picture into rgb (width * height),
     * the sound into samples, at most max sample frames (a frame: one float
     * per channel). Returns the number of sample frames. */
    int (*frame)(const InputFrame *in, uint32_t *rgb, float *samples, int max);
    /* Why the game stopped (a crashed CPU), as lines for the picture, or NULL. */
    const char *(*halted)(char *buf, size_t len);
    int (*state_save)(const char *path);
    int (*state_load)(const char *path, char *err, size_t errlen);
    /* A key the system handles itself (an SDL keycode): a message for the
     * title bar, or NULL. */
    const char *(*key)(int key, char *buf, size_t len);
    /* Quitting: write saves and whatever else the game keeps. */
    void (*close)(void);
} System;

/* The systems this program links, NULL-terminated (generated by CMake). */
extern const System *const system_list[];

#endif
